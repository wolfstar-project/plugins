import { execFile } from "node:child_process";
import { mkdirSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { promisify } from "node:util";
import { err } from "@sapphire/result";
import { ApplicationCommandOptionType } from "discord-api-types/v10";
import { container, PreconditionError, RegisterCommand } from "@wolfstar/http-framework";
import {
  ChatInputApplicationCommandInteractionData,
  createTestHarness,
  makeCommand,
} from "@wolfstar/http-framework-test-utils";
import { build } from "tsdown";
import {
  clearSubcommandRegistries,
  Command,
  RegisterAsSubcommand,
  Subcommand,
  wireParentSubcommands,
} from "../src/index.js";
import "../src/register.js";

// `runPreconditions` exists since @wolfstar/http-framework 6.3.0, while the peer range still accepts ^3.1.0 and ^5.0.0.
// The plugin's own code sees a framework without it; the test harness keeps the real one.
vi.mock("@wolfstar/http-framework", async (importOriginal) => ({
  ...(await importOriginal<Record<string, unknown>>()),
  runPreconditions: undefined,
}));

const packageDirectory = fileURLToPath(new URL("../", import.meta.url));
// Inside the package, so the bare specifiers of the build resolve from its `node_modules`.
const outDir = fileURLToPath(
  new URL("../node_modules/.cache/older-framework-test/", import.meta.url),
);
const loader = fileURLToPath(
  new URL("fixtures/load-without-run-preconditions.mjs", import.meta.url),
);

describe("on a framework without runPreconditions", () => {
  afterEach(async () => {
    clearSubcommandRegistries();
    await container.stores.get("commands").unloadAll();
  });

  // The CI unit job runs vitest without a build, so the entries are built here. A named import of `runPreconditions`
  // would make Node refuse to link the build against an older framework, which no test of the sources can show.
  it("loads the built plugin", async () => {
    mkdirSync(outDir, { recursive: true });
    await build({
      config: false,
      cwd: packageDirectory,
      entry: { index: "src/index.ts", register: "src/register.ts" },
      outDir,
      format: "esm",
      platform: "node",
      dts: false,
      clean: true,
      deps: { neverBundle: true },
      tsconfig: fileURLToPath(new URL("../../../tsconfig.build.json", import.meta.url)),
      logLevel: "silent",
    });

    const entries = ["index.mjs", "register.mjs"].map(
      (name) => pathToFileURL(`${outDir}${name}`).href,
    );
    const { stdout } = await promisify(execFile)(process.execPath, [loader, ...entries]);

    expect(stdout.trim()).toBe("loaded");
  }, 60_000);

  it("runs a modular subcommand, without its preconditions option", async () => {
    @RegisterCommand({ name: "settings", description: "Settings" })
    class SettingsCommand extends Subcommand {}

    @RegisterAsSubcommand("settings", (builder) =>
      builder.setName("server").setDescription("Server settings"),
    )
    class ServerCommand extends Command {
      public constructor(context: Command.LoaderContext, options: Command.Options) {
        super(context, {
          ...options,
          preconditions: [
            () => err(new PreconditionError({ precondition: "administrator", message: "denied" })),
          ],
        });
      }

      public override chatInputRun(interaction: Command.ChatInputInteraction) {
        return interaction.reply({ content: "server" });
      }
    }

    const { runner } = createTestHarness({
      subcommandsAdvanced: { nameCommandsAutogenerated: true },
    });
    const child = makeCommand(ServerCommand);
    const parent = makeCommand(SettingsCommand);

    const store = container.stores.get("commands");
    await store.unloadAll();
    wireParentSubcommands(parent);
    store.set(child.name, child);
    store.set(parent.name, parent);
    store.router.addChatInputMapping("settings", parent);

    const result = await runner.run({
      ...ChatInputApplicationCommandInteractionData,
      data: {
        id: "0",
        name: "settings",
        type: 1,
        options: [{ type: ApplicationCommandOptionType.Subcommand, name: "server", options: [] }],
      },
    });

    expect(result.statusCode).toBe(200);
    expect(result.json()).toMatchObject({ data: { content: "server" } });
  });
});
