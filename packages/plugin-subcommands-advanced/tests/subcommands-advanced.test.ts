async function loadParentAndChildren(
  parent: ReturnType<typeof makeCommand>,
  children: ReturnType<typeof makeCommand>[],
) {
  const store = container.stores.get("commands");
  await store.unloadAll();

  wireParentSubcommands(parent);

  for (const child of children) {
    store.set(child.name, child);
  }

  store.set(parent.name, parent);
  if (parent.router.chatInputName) {
    store.router.addChatInputMapping(parent.router.chatInputName, parent);
  }
}

const optionNames = (options: { name: string }[]) => options.map((option) => option.name);

describe("plugin-subcommands-advanced", () => {
  afterEach(async () => {
    clearSubcommandRegistries();
    await container.stores.get("commands").unloadAll();
  });

  it("wires a modular subcommand onto the parent and runs the child chatInputRun", async () => {
    let builderCalls = 0;

    @RegisterCommand({ name: "utils", description: "Utility commands" })
    class UtilsCommand extends Subcommand {}

    @RegisterAsSubcommand("utils", (builder) => {
      builderCalls++;
      return builder.setName("ping").setDescription("Ping the bot");
    })
    class PingCommand extends Command {
      public override chatInputRun(interaction: Command.ChatInputInteraction) {
        return interaction.reply({ content: "Pong from child!" });
      }
    }

    const { runner } = createTestHarness({
      subcommandsAdvanced: { nameCommandsAutogenerated: true },
    });

    const ping = makeCommand(PingCommand);
    expect(builderCalls).toBe(0);

    const parent = makeCommand(UtilsCommand);
    await loadParentAndChildren(parent, [ping]);

    expect(builderCalls).toBe(1);
    expect(container.stores.get("commands").has("utils/ping")).toBe(true);
    expect(subCommandsRegistry.get("utils")?.has("ping")).toBe(true);
    expect(
      parent.router.routeChatInputInteraction({
        id: "0",
        name: "utils",
        type: 1,
        options: [{ type: ApplicationCommandOptionType.Subcommand, name: "ping", options: [] }],
      } as never),
    ).toBe("__wolfstar_sc_ping");

    const result = await runner.run({
      ...ChatInputApplicationCommandInteractionData,
      data: {
        id: "0",
        name: "utils",
        type: 1,
        options: [{ type: ApplicationCommandOptionType.Subcommand, name: "ping", options: [] }],
      },
    });

    expect(result.statusCode).toBe(200);
    expect(result.json()).toMatchObject({
      type: InteractionResponseType.ChannelMessageWithSource,
      data: { content: "Pong from child!" },
    });
  });

  it("wires a grouped modular subcommand", async () => {
    let translationsReady = false;
    let builderCalls = 0;

    @RegisterCommand((builder) =>
      builder
        .setName("utils")
        .setDescription("Utility commands")
        .addSubcommandGroup((group) => group.setName("poll").setDescription("Poll tools")),
    )
    class UtilsCommand extends Subcommand {}

    @RegisterAsSubcommandGroup("utils", "poll", (builder) => {
      builderCalls++;
      if (!translationsReady) throw new Error("translations are not ready");
      return builder.setName("create").setDescription("Create a poll");
    })
    class PollCreateCommand extends Command {
      public override chatInputRun(interaction: Command.ChatInputInteraction) {
        return interaction.reply({ content: "Poll created!" });
      }
    }

    const { runner } = createTestHarness({
      subcommandsAdvanced: { nameCommandsAutogenerated: true },
    });

    const create = makeCommand(PollCreateCommand);
    expect(builderCalls).toBe(0);

    translationsReady = true;
    const parent = makeCommand(UtilsCommand);
    await loadParentAndChildren(parent, [create]);

    expect(builderCalls).toBe(1);
    expect(create.name).toBe("utils/poll/create");

    const result = await runner.run({
      ...ChatInputApplicationCommandInteractionData,
      data: {
        id: "0",
        name: "utils",
        type: 1,
        options: [
          {
            type: ApplicationCommandOptionType.SubcommandGroup,
            name: "poll",
            options: [
              { type: ApplicationCommandOptionType.Subcommand, name: "create", options: [] },
            ],
          },
        ],
      },
    });

    expect(result.statusCode).toBe(200);
    expect(result.json()).toMatchObject({
      type: InteractionResponseType.ChannelMessageWithSource,
      data: { content: "Poll created!" },
    });
  });

  it("preserves framework-native subcommands when wiring modular children", async () => {
    @RegisterCommand({ name: "mixed", description: "Mixed commands" })
    class MixedCommand extends Subcommand {
      @RegisterSubcommandGroup((builder) => builder.setName("admin").setDescription("Admin tools"))
      @RegisterSubcommand((builder) => builder.setName("ban").setDescription("Ban a user"), "admin")
      public ban(interaction: Command.ChatInputInteraction) {
        return interaction.reply({ content: "native ban" });
      }

      @RegisterSubcommand((builder) =>
        builder.setName("native").setDescription("Native subcommand"),
      )
      public native(interaction: Command.ChatInputInteraction) {
        return interaction.reply({ content: "native!" });
      }
    }

    @RegisterAsSubcommand("mixed", (builder) =>
      builder.setName("modular").setDescription("Modular subcommand"),
    )
    class ModularCommand extends Command {
      public override chatInputRun(interaction: Command.ChatInputInteraction) {
        return interaction.reply({ content: "modular!" });
      }
    }

    const { runner } = createTestHarness({
      subcommandsAdvanced: { nameCommandsAutogenerated: true },
    });

    const modular = makeCommand(ModularCommand);
    const parent = makeCommand(MixedCommand);
    await loadParentAndChildren(parent, [modular]);

    const run = (options: object[]) =>
      runner.run({
        ...ChatInputApplicationCommandInteractionData,
        data: { id: "0", name: "mixed", type: 1, options },
      });

    const nativeResult = await run([
      { type: ApplicationCommandOptionType.Subcommand, name: "native", options: [] },
    ]);
    expect(nativeResult.statusCode).toBe(200);
    expect(nativeResult.json()).toMatchObject({ data: { content: "native!" } });

    const groupedNativeResult = await run([
      {
        type: ApplicationCommandOptionType.SubcommandGroup,
        name: "admin",
        options: [{ type: ApplicationCommandOptionType.Subcommand, name: "ban", options: [] }],
      },
    ]);
    expect(groupedNativeResult.statusCode).toBe(200);
    expect(groupedNativeResult.json()).toMatchObject({ data: { content: "native ban" } });

    const modularResult = await run([
      { type: ApplicationCommandOptionType.Subcommand, name: "modular", options: [] },
    ]);
    expect(modularResult.statusCode).toBe(200);
    expect(modularResult.json()).toMatchObject({ data: { content: "modular!" } });
  });

  it("supports registerSubCommand constructor options", async () => {
    let builderCalls = 0;

    @RegisterCommand({ name: "tools", description: "Tools" })
    class ToolsCommand extends Subcommand {}

    class EchoCommand extends Command {
      public constructor(context: Command.LoaderContext, options: Command.Options) {
        super(context, {
          ...options,
          registerSubCommand: {
            parentCommandName: "tools",
            slashSubcommand: (builder) => {
              builderCalls++;
              return builder.setName("echo").setDescription("Echo");
            },
          },
        });
      }

      public override chatInputRun(interaction: Command.ChatInputInteraction) {
        return interaction.reply({ content: "echo" });
      }
    }

    const { runner } = createTestHarness();
    const echo = makeCommand(EchoCommand);
    expect(builderCalls).toBe(0);

    const parent = makeCommand(ToolsCommand);
    await loadParentAndChildren(parent, [echo]);

    expect(builderCalls).toBe(1);

    const result = await runner.run({
      ...ChatInputApplicationCommandInteractionData,
      data: {
        id: "0",
        name: "tools",
        type: 1,
        options: [{ type: ApplicationCommandOptionType.Subcommand, name: "echo", options: [] }],
      },
    });

    expect(result.statusCode).toBe(200);
    expect(result.json()).toMatchObject({
      data: { content: "echo" },
    });
  });

  describe("preconditions of a subcommand piece", () => {
    const deny =
      (name: string): PreconditionFunction =>
      () =>
        err(new PreconditionError({ precondition: name, message: `${name} denied` }));
    const allow: PreconditionFunction = () => ok();

    function defineChildren(childPreconditions: Command.Options["preconditions"]) {
      const calls: string[] = [];

      @RegisterCommand((builder) =>
        builder
          .setName("settings")
          .setDescription("Settings")
          .addSubcommandGroup((group) => group.setName("roles").setDescription("Roles")),
      )
      class SettingsCommand extends Subcommand {}

      @RegisterAsSubcommand("settings", (builder) =>
        builder.setName("server").setDescription("Server settings"),
      )
      class ServerCommand extends Command {
        public constructor(context: Command.LoaderContext, options: Command.Options) {
          super(context, { ...options, preconditions: childPreconditions });
        }

        public override chatInputRun(interaction: Command.ChatInputInteraction) {
          calls.push("server");
          return interaction.reply({ content: "server" });
        }
      }

      @RegisterAsSubcommandGroup("settings", "roles", (builder) =>
        builder.setName("add").setDescription("Add a role"),
      )
      class RolesAddCommand extends Command {
        public constructor(context: Command.LoaderContext, options: Command.Options) {
          super(context, { ...options, preconditions: childPreconditions });
        }

        public override chatInputRun(interaction: Command.ChatInputInteraction) {
          calls.push("roles add");
          return interaction.reply({ content: "roles add" });
        }
      }

      return { calls, SettingsCommand, ServerCommand, RolesAddCommand };
    }

    async function setup(childPreconditions: Command.Options["preconditions"]) {
      const { calls, SettingsCommand, ServerCommand, RolesAddCommand } =
        defineChildren(childPreconditions);
      const { runner } = createTestHarness({
        subcommandsAdvanced: { nameCommandsAutogenerated: true },
      });

      const denied: string[] = [];
      container.client.on("chatInputCommandDenied", (error: PreconditionError) => {
        denied.push(error.precondition);
      });
      // A denial is handed to `handleError`, which emits `error`: without a listener it would throw.
      container.client.on("error", () => {});

      const children = [makeCommand(ServerCommand), makeCommand(RolesAddCommand)];
      const parent = makeCommand(SettingsCommand);
      await loadParentAndChildren(parent, children);

      const run = (options: object[]) =>
        runner.run({
          ...ChatInputApplicationCommandInteractionData,
          data: { id: "0", name: "settings", type: 1, options },
        });

      return { calls, denied, parent, run };
    }

    const direct = [{ type: ApplicationCommandOptionType.Subcommand, name: "server", options: [] }];
    const grouped = [
      {
        type: ApplicationCommandOptionType.SubcommandGroup,
        name: "roles",
        options: [{ type: ApplicationCommandOptionType.Subcommand, name: "add", options: [] }],
      },
    ];

    it.each([
      ["a direct subcommand", direct],
      ["a grouped subcommand", grouped],
    ])("denies %s whose piece precondition fails, without running it", async (_, options) => {
      const { calls, denied, run } = await setup([deny("administrator")]);

      await run(options);

      expect(calls).toEqual([]);
      expect(denied).toEqual(["administrator"]);
    });

    it.each([
      ["a direct subcommand", direct, "server"],
      ["a grouped subcommand", grouped, "roles add"],
    ])("runs %s whose piece preconditions pass", async (_, options, content) => {
      const { calls, denied, run } = await setup([allow]);

      const result = await run(options);

      expect(calls).toEqual([content]);
      expect(denied).toEqual([]);
      expect(result.statusCode).toBe(200);
      expect(result.json()).toMatchObject({ data: { content } });
    });

    it("runs the parent preconditions before those of the subcommand piece", async () => {
      const { calls, denied, parent, run } = await setup([deny("child")]);
      Reflect.set(parent.options, "preconditions", [deny("parent")]);

      await run(direct);

      expect(calls).toEqual([]);
      expect(denied).toEqual(["parent"]);
    });
  });

  describe("subcommand order", () => {
    const childNames = ["unblock", "block", "history"];

    function defineChildren(groupName?: string) {
      return childNames.map((name) => {
        const decorate = groupName
          ? RegisterAsSubcommandGroup("reports", groupName, (builder) =>
              builder.setName(name).setDescription(name),
            )
          : RegisterAsSubcommand("reports", (builder) =>
              builder.setName(name).setDescription(name),
            );

        @decorate
        class Child extends Command {
          public override chatInputRun(interaction: Command.ChatInputInteraction) {
            return interaction.reply({ content: name });
          }
        }

        return Child;
      });
    }

    function wireInOrder(order: number[], grouped: boolean) {
      createTestHarness({ subcommandsAdvanced: { nameCommandsAutogenerated: true } });

      @RegisterCommand((builder) => {
        builder.setName("reports").setDescription("Reports");
        if (grouped) builder.addSubcommandGroup((group) => group.setName("g").setDescription("g"));
        return builder.addSubcommand((sub) => sub.setName("native").setDescription("native"));
      })
      class ReportsCommand extends Subcommand {}

      const classes = defineChildren(grouped ? "g" : undefined);
      for (const index of order) makeCommand(classes[index]!);
      const parent = makeCommand(ReportsCommand);
      wireParentSubcommands(parent);

      const options = applicationCommandRegistry.get(ReportsCommand)!.chatInput!.toJSON().options!;
      return { parent, options };
    }

    const findGroup = (options: ReturnType<typeof wireInOrder>["options"]) =>
      options.find(
        (option) => option.type === ApplicationCommandOptionType.SubcommandGroup,
      ) as unknown as { options: { name: string }[] };

    it("wires direct subcommands in the same order whatever order they loaded in", () => {
      const forward = wireInOrder([0, 1, 2], false).options;
      clearSubcommandRegistries();
      const backward = wireInOrder([2, 1, 0], false).options;

      expect(optionNames(forward)).toEqual(["native", "block", "history", "unblock"]);
      expect(backward).toEqual(forward);
    });

    it("wires grouped subcommands in the same order whatever order they loaded in", () => {
      const forward = wireInOrder([0, 1, 2], true).options;
      clearSubcommandRegistries();
      const backward = wireInOrder([2, 1, 0], true).options;

      expect(optionNames(findGroup(forward).options)).toEqual(["block", "history", "unblock"]);
      expect(backward).toEqual(forward);
    });

    it("attaches subcommands and groups to a builder sorted by name", () => {
      const direct = wireInOrder([0, 1, 2], false);
      const directBuilder = new SlashCommandBuilder().setName("reports").setDescription("Reports");
      RegisterSubcommandsHooks.subcommands(direct.parent, directBuilder);
      expect(optionNames(directBuilder.toJSON().options as { name: string }[])).toEqual([
        "block",
        "history",
        "unblock",
      ]);

      clearSubcommandRegistries();
      const grouped = wireInOrder([2, 0, 1], true);
      const groupBuilder = new SlashCommandBuilder()
        .setName("reports")
        .setDescription("Reports")
        .addSubcommandGroup((group) => group.setName("g").setDescription("g"));
      RegisterSubcommandsHooks.groups(grouped.parent, groupBuilder);
      const [group] = groupBuilder.toJSON().options as { options: { name: string }[] }[];
      expect(optionNames(group!.options)).toEqual(["block", "history", "unblock"]);
    });
  });
});
